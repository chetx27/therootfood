import sharp from "sharp";
import { writeFileSync, readdirSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

async function blurDataUrl(imagePath) {
  const buffer = await sharp(imagePath)
    .resize(10)
    .webp({ quality: 20 })
    .toBuffer();
  return `data:image/webp;base64,${buffer.toString("base64")}`;
}

async function run() {
  const placeholders = {};

  const heroWebp = join(root, "public/hero.webp");
  placeholders["/hero.webp"] = await blurDataUrl(heroWebp);

  const productsDir = join(root, "public/products");
  for (const file of readdirSync(productsDir)) {
    if (file.endsWith(".webp")) {
      const key = `/products/${file}`;
      placeholders[key] = await blurDataUrl(join(productsDir, file));
    }
  }

  const out = `// Auto-generated by scripts/generate-blur-placeholders.mjs — do not edit manually
export const blurPlaceholders: Record<string, string> = ${JSON.stringify(placeholders, null, 2)};
`;
  writeFileSync(join(root, "lib/blur-placeholders.ts"), out);
  console.log(`Generated blur placeholders for ${Object.keys(placeholders).length} images`);
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
